#!/usr/bin/env python3
"""Emit the canonical normalized equation system for the 8A Belyi passport."""

from __future__ import annotations

import argparse


VARIABLES = (
    "alpha", "a0", "a1", "b0", "b1", "c4", "c2", "c1",
    *(f"u{i}" for i in range(8)),
    *(f"v{i}" for i in range(7)),
)


def emit_magma() -> None:
    names = ",".join(VARIABLES)
    u_tail = " + ".join(f"u{i}*x^{i}" for i in range(7, -1, -1))
    v_tail = " + ".join(f"v{i}*x^{i}" for i in range(6, -1, -1))
    print("// Generated by scripts/generate_8a_belyi_equations.py")
    print("// Ordered passport: (8,8,4,2,1)/(8,8,4,2,1)/(2^8,1^7)")
    print("// Normalize the unique 4-, 2-, and 1-fold points over 0 to 0, 1, infinity.")
    print(f"R<{names}> := PolynomialRing(Rationals(), 23, \"grevlex\");")
    print("S<x> := PolynomialRing(R);")
    print("A := x^2 + a1*x + a0;")
    print("B := x^2 + b1*x + b0;")
    print("P := alpha*A^8*x^4*(x-1)^2;")
    print("F := B^8*(x-c4)^4*(x-c2)^2*(x-c1);")
    print(f"U := x^8 + {u_tail};")
    print(f"V := x^7 + {v_tail};")
    print("Q := U^2*V;")
    print("full_equations := [Coefficient(P + F - Q, i) : i in [0..22]];")
    print("assert #full_equations eq 23;")
    print()
    print("// Smaller elimination presentation: U divides H and its derivative.")
    print("H := P + F;")
    print("remainder_H := H mod U;")
    print("remainder_dH := Derivative(H) mod U;")
    print("reduced_equations :=")
    print("    [Coefficient(remainder_H, i) : i in [0..7]] cat")
    print("    [Coefficient(remainder_dH, i) : i in [0..7]];")
    print("assert #reduced_equations eq 16;")
    print()
    print("// On a solution, phi := P/H and phi-1 := -F/H.")
    print("// Saturate away collisions and require U squarefree and H/U^2 squarefree")
    print("// and coprime to U. Passport conditions alone do not certify M23 monodromy.")


def emit_sage() -> None:
    names = ", ".join(repr(name) for name in VARIABLES)
    unpack = ", ".join(VARIABLES)
    u_tail = " + ".join(f"u{i}*x**{i}" for i in range(7, -1, -1))
    v_tail = " + ".join(f"v{i}*x**{i}" for i in range(6, -1, -1))
    print("# Generated by scripts/generate_8a_belyi_equations.py --format sage")
    print("# Ordered passport: (8,8,4,2,1)/(8,8,4,2,1)/(2^8,1^7)")
    print("# Normalize the unique 4-, 2-, and 1-fold points over 0 to 0, 1, infinity.")
    print(f"R = PolynomialRing(QQ, names=({names}), order=\"degrevlex\")")
    print(f"({unpack}) = R.gens()")
    print("S = PolynomialRing(R, names=(\"x\",))")
    print("x = S.gen()")
    print("A = x**2 + a1*x + a0")
    print("B = x**2 + b1*x + b0")
    print("P = alpha*A**8*x**4*(x-1)**2")
    print("F = B**8*(x-c4)**4*(x-c2)**2*(x-c1)")
    print(f"U = x**8 + {u_tail}")
    print(f"V = x**7 + {v_tail}")
    print("Q = U**2*V")
    print("full_equations = [(P + F - Q)[i] for i in range(23)]")
    print("assert len(full_equations) == 23")
    print()
    print("# Smaller elimination presentation: U divides H and its derivative.")
    print("H = P + F")
    print("remainder_H = H % U")
    print("remainder_dH = H.derivative() % U")
    print("reduced_equations = (")
    print("    [remainder_H[i] for i in range(8)]")
    print("    + [remainder_dH[i] for i in range(8)]")
    print(")")
    print("assert len(reduced_equations) == 16")
    print()
    print("# On a solution, phi := P/H and phi-1 := -F/H.")
    print("# Saturate away collisions and require U squarefree and H/U^2 squarefree")
    print("# and coprime to U. Passport conditions alone do not certify M23 monodromy.")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--format",
        choices=("magma", "sage"),
        default="magma",
        help="computer-algebra syntax to emit (default: magma)",
    )
    args = parser.parse_args()
    if args.format == "magma":
        emit_magma()
    else:
        emit_sage()


if __name__ == "__main__":
    main()
