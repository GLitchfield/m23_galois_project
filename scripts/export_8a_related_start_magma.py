#!/usr/bin/env python3
"""Export the exact (4A,3A,8A) related-start classes to Magma syntax."""

from __future__ import annotations

import argparse
import csv
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "derived" / "m23_4a_3a_8a_inner_classes.tsv"


def parse_images(value: str) -> tuple[int, ...]:
    images = tuple(int(entry) - 1 for entry in value.split(","))
    if len(images) != 23 or set(images) != set(range(23)):
        raise ValueError("invalid degree-23 permutation")
    return images


def product(left: tuple[int, ...], right: tuple[int, ...]) -> tuple[int, ...]:
    return tuple(right[left[point]] for point in range(23))


def magma_cycles(images: tuple[int, ...]) -> str:
    seen: set[int] = set()
    cycles = []
    for start in range(23):
        if start in seen:
            continue
        cycle = []
        point = start
        while point not in seen:
            seen.add(point)
            cycle.append(point + 1)
            point = images[point]
        if len(cycle) > 1:
            cycles.append("(" + ",".join(str(entry) for entry in cycle) + ")")
    return "".join(cycles) or "Id(S)"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", nargs="?", type=Path, default=SOURCE)
    args = parser.parse_args()
    source_bytes = args.source.read_bytes()
    lines = [line for line in source_bytes.decode().splitlines()
             if line and not line.startswith("#")]
    rows = list(csv.DictReader(lines, delimiter="\t"))
    if len(rows) != 54:
        raise ValueError("expected 54 generating source classes")

    triples = []
    class22_ids = []
    identity = tuple(range(23))
    for expected_id, row in enumerate(rows, 1):
        if int(row["source_class_id"]) != expected_id:
            raise ValueError("source IDs are not contiguous")
        entries = tuple(parse_images(row[column]) for column in
                        ("first_images", "second_images", "third_images"))
        if product(product(entries[0], entries[1]), entries[2]) != identity:
            raise ValueError(f"source class {expected_id} is not product one")
        triples.append(entries)
        if int(row["class22_link_count"]) > 0:
            class22_ids.append(expected_id)
    if class22_ids != [8, 27, 44]:
        raise ValueError("unexpected class-22 related-start source IDs")

    source_sha = hashlib.sha256(source_bytes).hexdigest()
    print("// Generated by scripts/export_8a_related_start_magma.py")
    print(f"// Source SHA-256: {source_sha}")
    print("// Passport: (4^4,2^2,1^3), (3^6,1^5), (8,8,4,2,1); genus 0")
    print("// Source IDs 8, 27, and 44 have exact four-point links to target class 22.")
    print("// Run from a clone of https://github.com/michaelmusty/Belyi:")
    print('// AttachSpec("Code/spec");')
    print("// X, phi := BelyiMap(sourceTriples[class22SourceIDs[1]]);")
    print()
    print("S := Sym(23);")
    print("sourceTriples := [")
    for class_id, entries in enumerate(triples, 1):
        suffix = "," if class_id < len(triples) else ""
        serialized = ", ".join(magma_cycles(entry) for entry in entries)
        print(f"  [ S | {serialized} ]{suffix} // source class {class_id}")
    print("];" )
    print("class22SourceIDs := [ 8, 27, 44 ];")
    print("assert forall{ sigma : sigma in sourceTriples | &*sigma eq Id(S) };")
    print("assert forall{ sigma : sigma in sourceTriples | #sub<S | sigma> eq 10200960 };")


if __name__ == "__main__":
    main()
