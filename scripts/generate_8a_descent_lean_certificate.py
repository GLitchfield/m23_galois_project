#!/usr/bin/env python3
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "derived" / "m23_8a_small_component_descent.tsv"


def lean_vector(values: list[int], width: int = 14) -> str:
    chunks = [values[index:index + width] for index in range(0, len(values), width)]
    body = ",\n    ".join(", ".join(str(value) for value in chunk) for chunk in chunks)
    return f"![{body}]"


def main() -> None:
    lines = [line for line in SOURCE.read_text().splitlines()
             if not line.startswith("#")]
    rows = list(csv.DictReader(lines, delimiter="\t"))
    assert len(rows) == 28

    full_images: dict[int, int] = {}
    symmetric_images: dict[int, int] = {}
    for row in rows:
        full_id = int(row["full_component_id"])
        full_image = int(row["complex_conjugate_full_component_id"])
        symmetric_id = int(row["symmetric_half_id"])
        symmetric_image = int(row["complex_conjugate_symmetric_half_id"])
        assert full_images.setdefault(full_id, full_image) == full_image
        assert symmetric_id not in symmetric_images
        symmetric_images[symmetric_id] = symmetric_image

    assert set(full_images) == set(range(1, 15))
    assert set(symmetric_images) == set(range(1, 29))
    full_zero_based = [full_images[index] - 1 for index in range(1, 15)]
    symmetric_zero_based = [symmetric_images[index] - 1 for index in range(1, 29)]

    print("import Mathlib.Data.Fin.Tuple.Reflection")
    print()
    print("/-!")
    print("Generated by `scripts/generate_8a_descent_lean_certificate.py` from")
    print("`data/derived/m23_8a_small_component_descent.tsv`. Do not edit by hand.")
    print("-/")
    print()
    print("namespace M23Formal.Certificates.Test0056")
    print()
    print("/-- Zero-based image table on the 14 full components. -/")
    print("def fullImage : Fin 14 → Fin 14 :=")
    print(f"  {lean_vector(full_zero_based)}")
    print()
    print("/-- Zero-based image table on the 28 six-element symmetry orbits. -/")
    print("def symmetricImage : Fin 28 → Fin 28 :=")
    print(f"  {lean_vector(symmetric_zero_based)}")
    print()
    print("end M23Formal.Certificates.Test0056")


if __name__ == "__main__":
    main()
